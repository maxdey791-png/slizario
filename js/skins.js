S.flagImages = new Map();
S.regionNames =
  typeof Intl.DisplayNames === "function"
    ? new Intl.DisplayNames(["ru"], { type: "region" })
    : null;
S.skinName = (id) =>
  id.startsWith("flag-")
    ? S.regionNames?.of(id.slice(5).toUpperCase()) || id.slice(5).toUpperCase()
    : S.skinNames[id] || "Лайм";
S.validSkin = (id) =>
  id in S.skinColors ||
  (id.startsWith("flag-") && S.countryCodes.includes(id.slice(5)));
S.getFlag = function (id) {
  if (!id.startsWith("flag-")) return null;
  let im = S.flagImages.get(id);
  if (!im) {
    im = new Image();
    im.src = "assets/flags/" + id.slice(5) + ".svg";
    S.flagImages.set(id, im);
  }
  return im.complete && im.naturalWidth ? im : null;
};
S.paletteCache = new Map();
S.skinColor = function (id) {
  if (S.paletteCache.has(id)) return S.paletteCache.get(id);
  if (S.skinColors[id]) return S.skinColors[id];
  let h = 0;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) % 360;
  const colors = ["hsl(" + h + " 75% 70%)", "hsl(" + h + " 65% 42%)"];
  S.paletteCache.set(id, colors);
  return colors;
};
S.randomSkin = () =>
  Math.random() < 0.65
    ? "flag-" +
      S.countryCodes[Math.floor(Math.random() * S.countryCodes.length)]
    : Object.keys(S.skinColors)[Math.floor(Math.random() * 6)];
if (!S.validSkin(S.config.skin)) S.config.skin = "lime";
